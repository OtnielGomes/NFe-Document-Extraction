"""Render the generated results file. Never edit that file by hand."""

from __future__ import annotations

from collections.abc import Sequence
from decimal import ROUND_HALF_UP, Decimal

from nfe_document_extraction.evaluation.metrics import ResultRow
from nfe_document_extraction.evaluation.scoring import DESCRIPTION_CORRECT_THRESHOLD

_COLUMNS = (
    "Extraction approach",
    "Rendition",
    "Origin",
    "Documents",
    "Field accuracy",
    "Description similarity",
    "Perfect-invoice rate",
    "Cost per invoice (USD)",
    "Latency median (s)",
    "Latency p95 (s)",
    "Errors caught by the validator",
    "Errors fixed by repair",
    "Errors reaching Human review",
    "Planted-error detection rate",
    "Extraction errors",
)


def render_results(
    rows: Sequence[ResultRow],
    *,
    model_snapshot: str,
    pricing_as_of: str,
) -> str:
    """Markdown table of Extraction approach × Rendition × origin."""
    lines = [
        "# Evaluation results",
        "",
        "Generated by `scripts/run_eval.py`. Do not edit by hand.",
        "",
        f"Model snapshot: `{model_snapshot}`. Pricing table date: {pricing_as_of}.",
        "",
        (
            "Description similarity is the normalized Levenshtein ratio after "
            "casefold, accent removal, and whitespace collapse. A description "
            f"is correct at >= {DESCRIPTION_CORRECT_THRESHOLD}."
        ),
        "",
        (
            "Field accuracy is an exact match after normalization. Product codes and "
            "descriptions are compared after casefold, accent removal, and whitespace "
            "collapse. Each missing item and each spurious item counts as one error. "
            "Planted-error documents are excluded from field accuracy and are scored "
            "by detection rate. Description similarity and the perfect-invoice rate "
            "still include them, because ground truth is the printed value."
        ),
        "",
        (
            "Latency p95 uses linear interpolation between closest ranks. "
            "Errors caught by the validator counts clean documents with at least one "
            "failing validation rule on the first reading. "
            "Errors fixed by repair counts clean documents accepted after the single "
            "Repair attempt. Errors reaching Human review counts clean documents whose "
            "outcome is Human review. The single-call baseline does not repair."
        ),
        "",
        (
            "Photo renditions are not applicable to the text-layer approach. "
            "It reads the PDF text layer and skips Simulated photos and Phone photos."
        ),
        "",
        (
            "Compare the digital PDF row with the simulated photo row of the same "
            "Extraction approach to see the accuracy drop from PDF to photo."
        ),
        "",
        "| " + " | ".join(_COLUMNS) + " |",
        "| " + " | ".join("---" for _ in _COLUMNS) + " |",
    ]
    lines.extend(_row(row) for row in rows)
    lines.append("")
    return "\n".join(lines)


def _row(row: ResultRow) -> str:
    if not row.applicable:
        gaps = ("n/a",) * (len(_COLUMNS) - 3)
        cells = (row.approach, row.rendition, row.origin, *gaps)
        return "| " + " | ".join(cells) + " |"
    cells = (
        row.approach,
        row.rendition,
        row.origin,
        str(row.documents),
        _decimal(row.field_accuracy, "0.0001"),
        _decimal(row.description_similarity, "0.0001"),
        _decimal(row.perfect_invoice_rate, "0.0001"),
        _decimal(row.cost_per_invoice_usd, "0.000001"),
        f"{row.latency_median_seconds:.3f}",
        f"{row.latency_p95_seconds:.3f}",
        str(row.validator_errors_caught),
        str(row.errors_fixed_by_repair),
        str(row.errors_reaching_human_review),
        _decimal(row.planted_detection_rate, "0.0001"),
        str(row.extraction_failures),
    )
    return "| " + " | ".join(cells) + " |"


def _decimal(value: Decimal | None, places: str) -> str:
    if value is None:
        return "n/a"
    quantized = value.quantize(Decimal(places), rounding=ROUND_HALF_UP)
    return f"{quantized:f}"
